def sheet_system(region: str) -> str:
    hint = REGION_HINTS.get(region, "")
    return f"{KB_EXCERPT}\n[이 계열의 판독 지침]\n{hint}\n"


MERGE_RULES = """\
당신은 한 계열(도면 묶음)의 시트별 판독 결과를 하나의 치수 정본으로 통합한다.

[통합 규칙]
- 같은 항목이 여러 시트에서 나오면 하나로 합치고, 근거는 가장 명확한 시트를 남긴다.
- **각 항목에 그 값이 실제로 적힌 시트의 ord 를 `ord` 필드로 그대로 남긴다.
  입력에 없는 ord 를 지어내지 않는다** — 이 값으로 도면 크롭을 자른다.
- 2개 이상 시트·뷰에서 일치 확인된 항목만 확정을 유지한다. 한 곳에서만 나온 값은
  추정으로 낮춘다(단일 소스 판독 금지).
- 값이 서로 다르면 그 자체가 애매성이다. **서로 다른 구간(존)을 본 것일 가능성**을
  선택지에 반드시 포함한다 — 실제로 '3열 vs 8열' 상충의 정답이 구간별 병존이었던
  사례가 있다.
- 시트별 판독의 애매성은 중복을 제거해 승계한다(ord 는 원 시트를 유지).
- notes 에 병합·교차확인 과정에서 판단한 근거를 남긴다.
"""

REVIEW_RULES = """\
당신은 판독 결과를 반박하는 검토자다. 판독자와 다른 사람이며, 통과시키는 것이
아니라 **틀린 곳을 찾는 것**이 임무다.

[반박 관점]
- 검산 없는 파생값, 합계가 맞지 않는 체인
- 단일 소스인데 확정으로 표기된 값
- 구간(존)이 다를 가능성을 무시하고 하나로 뭉갠 값
- 도면 간 표기 상충을 애매성으로 올리지 않고 임의 선택한 값
- 근거 좌표가 값의 위치와 어긋나 보이는 항목

[판정]
- 기각: 반박을 시도했으나 판독이 옳다. 이유를 적는다.
- 상태변경: 추정 또는 검토지적으로 **낮춘다**. new_status 필수(승격은 불가).
- 신규애매성: 사용자에게 물어야 한다. new_ambiguity 필수(선택지 2~4·각 근거·모델 영향·
  통합 결과에 있던 ord).

확신이 없으면 상태변경(추정)을 택한다. 추정을 확정처럼 두는 것이 가장 큰 사고다.
"""


def merge_system(region: str) -> str:
    return f"{KB_EXCERPT}\n{MERGE_RULES}\n[이 계열]\n{REGION_HINTS.get(region, '')}\n"


def review_system(region: str) -> str:
    return f"{KB_EXCERPT}\n{REVIEW_RULES}\n[이 계열]\n{REGION_HINTS.get(region, '')}\n"
